function [c, tau, starts] = correlation_trace(x, tx, directStart, fs)
%CORRELATION_TRACE Sliding complex matched-filter output versus pulse start.
x = x(:); tx = tx(:);
c = conv(x, conj(flipud(tx)), 'valid');
starts = (1:numel(c)).';
tau = (starts-directStart)/fs;
end
